// --- HELPER FUNKCIJE ---

function dukatIconHtml(extraClass = '') {
    const className = `dukat-icon-inline${extraClass ? ` ${extraClass}` : ''}`;
    return `<svg class="${className}" aria-hidden="true" focusable="false"><use href="#app-icon-dukat"></use></svg>`;
}

function formatDukatIcons(value) {
    if (typeof value !== 'string') return value;
    return value.replace(/\{DUKAT_ICON\}/g, dukatIconHtml());
}

function t(key) {
    const lang = localStorage.getItem('yamb_lang') || 'sr';
    if (TRANSLATIONS[lang] && TRANSLATIONS[lang].hasOwnProperty(key)) {
        return formatDukatIcons(TRANSLATIONS[lang][key]);
    }
    return key;
}

function setLanguage(lang) {
    if (lang !== 'sr' && lang !== 'en') return;
    localStorage.setItem('yamb_lang', lang);
    location.reload(); 
}

function applyTranslations() {
    document.querySelectorAll('[data-lang]').forEach(el => {
        const key = el.getAttribute('data-lang');
        if (key) el.innerHTML = t(key); // Koristimo innerHTML zbog <b> i <strong> tagova
    });

    document.querySelectorAll('[data-lang-title]').forEach(el => {
        const key = el.getAttribute('data-lang-title');
        if (key) el.title = t(key);
    });

    document.querySelectorAll('[data-lang-aria]').forEach(el => {
        const key = el.getAttribute('data-lang-aria');
        if (key) el.setAttribute('aria-label', t(key));
    });

    document.querySelectorAll('[data-lang-placeholder]').forEach(el => {
        const key = el.getAttribute('data-lang-placeholder');
        if (key) el.placeholder = t(key);
    });
    
    // Input polja
    const nameInput = document.getElementById('setting-name');
    if (nameInput) {
        nameInput.placeholder = t('settings_name_placeholder');
    }

    const globalChatInput = document.getElementById('global-chat-input');
    if (globalChatInput) {
        globalChatInput.placeholder = t('global_chat_placeholder');
    }

    const btnUndo = document.getElementById('btn-undo-move');
    if (btnUndo) {
        btnUndo.title = t('undo_title');
    }
    
    // NOVO: Ažuriranje 'title' atributa za tooltipove u meniju
    document.querySelectorAll('.btn-square').forEach(btn => {
        const onclickAttr = btn.getAttribute('onclick');
        if (onclickAttr) {
            if (onclickAttr.includes('dailyManager.open()')) btn.title = t('menu_daily');
            if (onclickAttr.includes('showHighscoresScreen()')) btn.title = t('menu_hs').replace('🏆 ', '');
            if (onclickAttr.includes('showStats()')) btn.title = t('menu_stats');
            if (onclickAttr.includes('showSettings()')) btn.title = t('menu_settings').replace('⚙ ', '');
            if (onclickAttr.includes('showRules()')) btn.title = t('menu_rules').replace('📖 ', '');
        }
    });

    document.querySelectorAll('.btn-special-square').forEach(btn => {
        const onclickAttr = btn.getAttribute('onclick');
        if (onclickAttr) {
            if (onclickAttr.includes('riznicaManager.open()')) btn.title = t('menu_shop').replace('💎 ', '');
            if (onclickAttr.includes('openTournament()')) btn.title = t('tourney_title');
        }
    });
}

document.addEventListener('DOMContentLoaded', () => {
    applyTranslations();
});
